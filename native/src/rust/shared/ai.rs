//! Self-built AI assistant + settings model (T2.5) — mirrors the backend AI types
//! (`src-tauri/src/ai/types.rs`).
//!
//! The native shell owns its own model; the backend (B5) maps these to the `ai_*`
//! public API when it lands.
#![allow(dead_code)] // candidates/context helpers are exercised once the B5 backend lands

/// AI configuration (provider/base_url/model + privacy). API key never persisted.
#[derive(Debug, Clone, Default)]
pub struct AiConfig {
    pub provider: String,
    pub base_url: String,
    pub model: String,
    pub privacy_mode: bool,
    pub api_key: String,
}

impl AiConfig {
    /// Provider label shown in the settings panel.
    pub fn provider_label(&self) -> &str {
        match self.provider.as_str() {
            "cloud" => "云端",
            "ollama" => "Ollama",
            _ => "自动",
        }
    }
}

/// Terminal context sent to the AI for inference (uses `TerminalContext` naming).
#[derive(Debug, Clone, Default)]
pub struct TerminalContext {
    pub cwd: Option<String>,
    pub shell: Option<String>,
    pub recent_commands: Vec<String>,
    pub recent_output: Option<String>,
    pub last_exit_code: Option<i32>,
    pub os: Option<String>,
}

/// A command candidate generated by AI.
#[derive(Debug, Clone)]
pub struct CommandCandidate {
    pub command: String,
    pub explanation: String,
    pub confidence: f64,
}

/// A completion candidate for inline shell completion.
#[derive(Debug, Clone)]
pub struct CompletionCandidate {
    pub text: String,
    pub description: Option<String>,
    pub confidence: f64,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn provider_labels() {
        let label = |provider: &str| {
            AiConfig {
                provider: provider.into(),
                ..Default::default()
            }
            .provider_label()
            .to_string()
        };
        assert_eq!(label("cloud"), "云端");
        assert_eq!(label("ollama"), "Ollama");
        assert_eq!(label("auto"), "自动");
    }

    #[test]
    fn context_defaults_blank() {
        let t = TerminalContext::default();
        assert!(t.cwd.is_none() && t.recent_commands.is_empty());
    }
}
